/* Builds the single-file desktop plugin: src/pane.js (Taste Roll and the taste
 * learner) with the vendored Resonant Field theme folded in where pane.js says
 * @@RESONANT_FIELD@@. Hermes Desktop loads one ES module per plugin and rewrites
 * only '@hermes/plugin-sdk' and 'react', so the theme is wrapped in a function
 * scope, reads the SDK off the namespace (older builds without THEMES_AREA still
 * load) and gets a jsx() shim over createElement instead of react/jsx-runtime.
 *
 *   node build.mjs           write plugin.js
 *   node build.mjs --check   exit 1 if plugin.js is not what this would write
 */
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync, renameSync } from 'node:fs'

const here = (p) => new URL(p, import.meta.url)
const fail = (msg) => { console.error(`build.mjs: ${msg}`); process.exit(1) }

const source = JSON.parse(readFileSync(here('theme/SOURCE.json'), 'utf8'))
const themeBytes = readFileSync(here('theme/resonant-field.js'))
const sha = createHash('sha256').update(themeBytes).digest('hex')
if (sha !== source.sha256) fail(`theme/resonant-field.js sha256 ${sha} does not match theme/SOURCE.json (${source.sha256}).`)

let theme = themeBytes.toString('utf8')
const sdkImport = /^import \{([^}]*)\} from '@hermes\/plugin-sdk'\n/m
const names = theme.match(sdkImport)
if (!names) fail('theme: no @hermes/plugin-sdk import line found.')
theme = theme.replace(sdkImport, '')
if (!/^import \{ jsx, jsxs \} from 'react\/jsx-runtime'\n/m.test(theme)) fail('theme: unexpected jsx-runtime import.')
theme = theme.replace(/^import \{ jsx, jsxs \} from 'react\/jsx-runtime'\n/m, '')
if (theme.split('\nexport default {').length !== 2) fail('theme: expected exactly one `export default {`.')
theme = theme.replace('\nexport default {', '\nconst RF_PLUGIN = {')
if (/^\s*(import|export)\b/m.test(theme)) fail('theme: an import or export survived the rewrite.')

const block = [
  `/* ---- Resonant Field theme (GENERATED by build.mjs; do not edit here) -------`,
  ` * ${source.project} ${source.version} @ ${source.commit}, ${source.path}`,
  ` * sha256 ${source.sha256}. Edit the theme in its own repo, re-vendor it,`,
  ` * then rebuild. */`,
  `const RF = (() => {`,
  `  const {${names[1]}} = SDK`,
  `  const jsx = (type, props, key) => h(type, key === undefined ? props : { ...props, key })`,
  `  const jsxs = jsx`,
  theme.trim(),
  `  return Object.freeze({ plugin: RF_PLUGIN, PRESETS, palette, contrast, buildTheme, PLATES, FONT_URL })`,
  `})()`,
  `/* ---- end Resonant Field ---------------------------------------------------- */`
].join('\n')

const pane = readFileSync(here('src/pane.js'), 'utf8')
const MARK = '/* @@RESONANT_FIELD@@ */'
if (pane.split(MARK).length !== 2) fail(`src/pane.js must contain ${MARK} exactly once.`)
const out = `// GENERATED by build.mjs from src/pane.js + theme/. Edit those, then run node build.mjs.\n${pane.replace(MARK, block)}`

for (const m of out.matchAll(/^import .* from '([^']+)'/gm)) {
  if (m[1] !== '@hermes/plugin-sdk' && m[1] !== 'react') fail(`disallowed import '${m[1]}'.`)
}
if (/\beval\(|new Function\(|\bimport\(/.test(out)) fail('eval, new Function or dynamic import in the output.')

const dest = here('plugin.js')
if (process.argv.includes('--check')) {
  let cur = ''
  try { cur = readFileSync(dest, 'utf8') } catch {}
  if (cur !== out) fail('plugin.js is stale: run `node build.mjs` and commit it.')
  console.log(`plugin.js is current (${Math.round(out.length / 1024)} KiB)`)
} else {
  writeFileSync(here('plugin.js.tmp'), out)
  renameSync(here('plugin.js.tmp'), dest)
  console.log(`wrote plugin.js (${Math.round(out.length / 1024)} KiB)`)
}
