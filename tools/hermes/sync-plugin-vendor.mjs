#!/usr/bin/env node
/**
 * Vendor the Tastecheck CLI closure into the Hermes plugin.
 *
 *   node tools/hermes/sync-plugin-vendor.mjs          copy the files + rewrite MANIFEST.json
 *   node tools/hermes/sync-plugin-vendor.mjs --check  exit 1 if the vendored copy drifted
 *
 * The plugin runs ONLY these files (bin/tastecheck.mjs audit|profile|--version), verifies
 * each against MANIFEST.json before every run, and never fetches code from the network.
 */
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const repo = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const vendorRoot = join(repo, "plugins", "tastecheck-hermes", "vendor");
const dest = join(vendorRoot, "tastecheck");
const manifestPath = join(vendorRoot, "MANIFEST.json");

// The CLI closure the plugin exercises: entry point, its two dynamic imports' needs for
// `profile`, the version source, and the browser audit runner + in-page probe.
export const FILES = [
  "bin/tastecheck.mjs",
  "bin/profile.mjs",
  "tools/lib/main-entry.mjs",
  "package.json",
  "skills/tastecheck-pass/assets/cdp-qa.mjs",
  "skills/tastecheck-pass/assets/gate-audit.js",
  "LICENSE",
];

const sha = (buf) => createHash("sha256").update(buf).digest("hex");

function expected() {
  const files = {};
  for (const rel of FILES) files[rel] = sha(readFileSync(join(repo, rel)));
  return { schema: 1, note: "Generated by tools/hermes/sync-plugin-vendor.mjs; do not edit by hand.", files };
}

function walk(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).flatMap((n) => {
    const p = join(dir, n);
    return statSync(p).isDirectory() ? walk(p) : [relative(dest, p).split("\\").join("/")];
  });
}

const want = expected();
const wantText = JSON.stringify(want, null, 2) + "\n";

if (process.argv.includes("--check")) {
  const problems = [];
  const have = existsSync(manifestPath) ? readFileSync(manifestPath, "utf8") : "";
  if (have !== wantText) problems.push("vendor/MANIFEST.json is stale");
  for (const rel of FILES) {
    const p = join(dest, rel);
    if (!existsSync(p)) problems.push(`missing vendor/tastecheck/${rel}`);
    else if (sha(readFileSync(p)) !== want.files[rel]) problems.push(`vendor/tastecheck/${rel} differs from ${rel}`);
  }
  for (const rel of walk(dest)) if (!FILES.includes(rel)) problems.push(`unexpected vendor/tastecheck/${rel}`);
  if (problems.length) {
    console.error(problems.map((p) => `vendor drift: ${p}`).join("\n"));
    console.error("fix: node tools/hermes/sync-plugin-vendor.mjs");
    process.exit(1);
  }
  console.log(`vendor ok (${FILES.length} files)`);
} else {
  rmSync(dest, { recursive: true, force: true });
  for (const rel of FILES) {
    const out = join(dest, rel);
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, readFileSync(join(repo, rel)));
  }
  writeFileSync(manifestPath, wantText);
  console.log(`vendored ${FILES.length} files into ${relative(repo, dest)}`);
}
